  function parse(def) {
    let raw = false, s = def;
    if (s[0] === '!') { raw = true; s = s.slice(1); }
    let top = 0; const m = s.match(/^(\d+):/); if (m) { top = +m[1]; s = s.slice(m[0].length); }
    const rows = s.split('|'); const w = Math.max(...rows.map((r) => r.length));
    const px = [];
    rows.forEach((r, j) => { for (let i = 0; i < r.length; i++) if (r[i] === '#') px.push([i, top + j]); });
    return { w, px, raw };
  }
  // atlas: glyph cells laid out on a strip; one white-ink and one black-ink copy
  function build(defs, bold, capTop, cellH, space) {
    const keys = Object.keys(defs), gl = {};
    keys.forEach((k) => (gl[k] = parse(defs[k])));
    const CW = 14;
    const mk = (col) => {
      const c = document.createElement('canvas'); c.width = keys.length * CW; c.height = cellH; const g = c.getContext('2d'); g.fillStyle = col;
      keys.forEach((k, i) => { const q = gl[k]; for (const [x, y] of q.px) { g.fillRect(i * CW + x, capTop + y, 1, 1); if (bold && !q.raw) g.fillRect(i * CW + x + 1, capTop + y, 1, 1); } });
      return c;
    };
    const map = {};
    keys.forEach((k, i) => { const q = gl[k]; const w = q.w + (bold && !q.raw ? 1 : 0); map[k] = { sx: i * CW, w, adv: w + 1 }; });
    map[' '] = { sx: 0, w: 0, adv: space, blank: true };
    return { atlas: { '#000000': mk('#000000'), '#ffffff': mk('#ffffff') }, map, capTop, cellH };
  }
  const FONTS = {};
  function init() {
    if (FONTS.chicago) return;
    FONTS.chicago = build(CHI, true, 3, 16, 5);   // menu bar, titles, buttons, dialogs
    FONTS.g12 = build(CHI, false, 3, 16, 4);      // chat text
    FONTS.g9 = build(G9, false, 2, 12, 3);        // icon names, small print
    FONTS.g9b = build(G9, true, 2, 12, 4);
  }
  // draw text with its cap top at (x, y). Returns advance width.
  function text(ctx, s, x, y, f = 'chicago', col = '#000000') {
    const F = FONTS[f], img = F.atlas[col];
    let cx = Math.round(x); const ty = Math.round(y) - F.capTop;
    for (const ch of s) {
      const m = F.map[ch] || F.map['?'];
      if (!m.blank) ctx.drawImage(img, m.sx, 0, m.w, F.cellH, cx, ty, m.w, F.cellH);
      cx += m.adv;
    }
    return cx - Math.round(x);
  }
  function measure(s, f = 'chicago') { const F = FONTS[f]; let w = 0; for (const ch of s) w += (F.map[ch] || F.map['?']).adv; return w > 0 ? w - 1 : 0; }
  function wrap(s, maxW, f) {
    const out = [];
    for (const para of s.split('\n')) {
      const words = para.split(' '); let line = '';
      for (const w of words) { const cand = line ? line + ' ' + w : w; if (measure(cand, f) > maxW && line) { out.push(line); line = w; } else line = cand; }
      out.push(line);
    }
    return out;
  }
  G.FONT = { init, text, measure, wrap, FONTS, CHI, G9 };
