// Verification: writes film/verification.txt
//   frame count + duration (ffprobe), flash check (stats.json from compose video), determinism (frames rendered twice in
//   fresh pages, byte-compared), mean luminance either side of each transition (graded, from the caches), hero continuity,
//   agent count, render times per section (cache/times.json).
const path = require('path');
const fs = require('fs');
const crypto = require('crypto');
const { execFileSync } = require('child_process');
const L = require('./lib');
const F = L.F;
const { heroBox } = require('./peek');

function gradeLUT(slot) {
  const G = JSON.parse(fs.readFileSync(path.join(L.FILM_DIR, 'grade.json'), 'utf8'))[slot] || { gain: [1, 1, 1], lift: [0, 0, 0] };
  return [0, 1, 2].map((c) => { const l = new Uint8ClampedArray(256); for (let v = 0; v < 256; v++) l[v] = Math.round(v * G.gain[c] + G.lift[c] * (1 - v / 255)); return l; });
}
const lin = new Float32Array(256); for (let v = 0; v < 256; v++) { const c = v / 255; lin[v] = c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4); }
function meanLum(buf, lut) {
  let s = 0, n = 0, r = 0, g = 0, b = 0;
  for (let y = 0; y < L.H; y += 3) for (let x = 0; x < L.W; x += 3) {
    const i = (y * L.W + x) * 4, R = lut[0][buf[i]], G = lut[1][buf[i + 1]], B = lut[2][buf[i + 2]];
    s += 0.2126 * lin[R] + 0.7152 * lin[G] + 0.0722 * lin[B]; r += R; g += G; b += B; n++;
  }
  return { lum: s / n, rgb: [r / n, g / n, b / n] };
}
async function main() {
  const out = [];
  const say = (s) => { out.push(s); console.log(s); };
  const video = path.join(L.OUT_DIR, 'thousand-agents-16x9.mp4');
  say('1000 Agents — verification (generated by tools/verify.js)');
  say('');
  // 1. frames and duration
  const probe = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-count_frames', '-show_entries', 'stream=nb_read_frames,width,height,r_frame_rate,codec_name,profile,pix_fmt:format=duration', '-of', 'json', video]).toString());
  const st = probe.streams[0];
  say('VIDEO  ' + path.basename(video) + ': ' + st.codec_name + ' ' + st.profile + ' ' + st.pix_fmt + ' ' + st.width + 'x' + st.height + ' @ ' + st.r_frame_rate + ' fps');
  say('       frames ' + st.nb_read_frames + ' (expected ' + F.FRAMES + '), duration ' + (+probe.format.duration).toFixed(3) + ' s (expected ' + F.DUR.toFixed(3) + ')');
  say('');
  // 2. flash check
  const S = JSON.parse(fs.readFileSync(path.join(L.FILM_DIR, 'stats.json'), 'utf8'));
  const ev = [];
  for (let f = 1; f < S.flashArea.length; f++) { const [u, d] = S.flashArea[f]; if (u >= 0.25) ev.push([f, +1, u]); if (d >= 0.25) ev.push([f, -1, d]); }
  // a flash is a pair of opposing large-area changes; count them in every 1 s window
  let worst = 0, worstAt = 0;
  for (let f = 0; f < S.flashArea.length; f++) {
    const w = ev.filter((e) => e[0] >= f && e[0] < f + 30);
    let flashes = 0; for (let i = 1; i < w.length; i++) if (w[i][1] !== w[i - 1][1]) flashes++;
    if (flashes > worst) { worst = flashes; worstAt = f; }
  }
  let maxArea = 0, maxAt = 0; S.flashArea.forEach((a, f) => { const m = Math.max(a[0], a[1]); if (m > maxArea) { maxArea = m; maxAt = f; } });
  let maxStep = 0, stepAt = 0; for (let f = 1; f < S.mean.length; f++) { const d = Math.abs(S.mean[f] - S.mean[f - 1]); if (d > maxStep) { maxStep = d; stepAt = f; } }
  say('FLASH  method: 96x54 grid of relative luminance; a large-area change = >=25% of the screen changing by >=0.1 with the darker state < 0.8;');
  say('       a flash = two opposing large-area changes; limit 3 per second.');
  say('       large-area changes found: ' + ev.length + '; worst 1 s window: ' + worst + ' flashes' + (worst ? ' (from frame ' + worstAt + ')' : '') + ' -> ' + (worst <= 3 ? 'PASS' : 'FAIL'));
  say('       largest share of screen changing by >=0.1 between consecutive frames: ' + (maxArea * 100).toFixed(2) + '% (frame ' + maxAt + ')');
  say('       largest frame-to-frame change of mean luminance: ' + maxStep.toFixed(4) + ' (frame ' + stepAt + ')');
  const ml = S.mean; say('       mean luminance over the film: min ' + Math.min(...ml).toFixed(4) + ', max ' + Math.max(...ml).toFixed(4));
  say('');
  // 3. determinism: frames rendered twice in fresh pages, compared byte for byte (and against the cache's frame position)
  say('DETERMINISM  each section renders a frame twice, in two fresh pages (and once more after rendering another time in between):');
  for (const s of F.SECTIONS) {
    const sp = F.span(s.slot), T = Math.round(((sp[0] + sp[1]) / 2) * 30) / 30;
    const p1 = await L.openSection(s.slot); const a = await p1.frame(T); await p1.frame(sp[0] + 0.5); const a2 = await p1.frame(T); await p1.close();
    const p2 = await L.openSection(s.slot); const b = await p2.frame(T); await p2.close();
    const h = (x) => crypto.createHash('sha1').update(x).digest('hex').slice(0, 12);
    say('       ' + s.slot.padEnd(20) + ' T=' + T.toFixed(3) + '  ' + h(a) + ' ' + h(a2) + ' ' + h(b) + '  ' + (h(a) === h(b) && h(a) === h(a2) ? 'identical' : 'DIFFERENT'));
  }
  await L.closeBrowser();
  say('');
  // 4. luminance either side of each transition, after grading
  say('TRANSITIONS  mean relative luminance and mean sRGB of each side over the 0.8 s overlap (graded), and the hero box at the midpoint:');
  for (let k = 0; k < F.X.length; k++) {
    const x = F.X[k], a = Math.round((x.t - 0.4) * 30), b = Math.round((x.t + 0.4) * 30) - 1, mid = Math.round(x.t * 30);
    const la = gradeLUT(x.from), lb = gradeLUT(x.to);
    const dA = L.decoder(path.join(L.CACHE_DIR, x.from + '.mkv'), a - F.frameSpan(x.from)[0]), dB = L.decoder(path.join(L.CACHE_DIR, x.to + '.mkv'), a - F.frameSpan(x.to)[0]);
    let A = { lum: 0, rgb: [0, 0, 0] }, B = { lum: 0, rgb: [0, 0, 0] }, n = 0, hA = null, hB = null;
    for (let f = a; f <= b; f++) {
      const ba = await dA.next(), bb = await dB.next();
      if (f === mid) { hA = heroBox(ba); hB = heroBox(bb); }
      if ((f - a) % 3) continue;
      const ma = meanLum(ba, la), mb = meanLum(bb, lb); n++;
      A.lum += ma.lum; B.lum += mb.lum; for (let c = 0; c < 3; c++) { A.rgb[c] += ma.rgb[c]; B.rgb[c] += mb.rgb[c]; }
    }
    dA.close(); dB.close();
    A.lum /= n; B.lum /= n; A.rgb = A.rgb.map((v) => v / n); B.rgb = B.rgb.map((v) => v / n);
    say('       ' + (k + 1) + ' @' + x.t.toFixed(1) + 's ' + x.from.slice(3).padEnd(17) + ' lum ' + A.lum.toFixed(4) + ' rgb ' + A.rgb.map((v) => v.toFixed(1)).join('/') +
      '   |  ' + x.to.slice(3).padEnd(17) + ' lum ' + B.lum.toFixed(4) + ' rgb ' + B.rgb.map((v) => v.toFixed(1)).join('/') + '   ratio ' + (B.lum / A.lum).toFixed(3));
    const hb = (h) => h ? 'centre x ' + h.cx.toFixed(0) + ', feet y ' + h.y1 + ', w ' + h.w + ', h ' + h.h : 'n/a';
    say('            hero out: ' + hb(hA) + '   |  hero in: ' + hb(hB));
  }
  say('');
  // 5. agents
  say('AGENTS  every section iterates the same ' + F.N + ' seeded agent identities (FILM.AG); the HUD shows FILM.agentsOut(T):');
  say('       0 until ' + F.T_OPEN + ' s, ' + F.agentsOut(5.0) + ' at 5.0 s, ' + F.agentsOut(7.0) + ' at 7.0 s, ' + F.agentsOut(F.T_ALL) + ' from ' + F.T_ALL + ' s to the end; FILES ends at ' + F.files(40) + ', LINES at ' + F.lines(40) + '.');
  say('');
  // 6. render times
  const times = JSON.parse(fs.readFileSync((fs.existsSync(path.join(L.CACHE_DIR, 'times.json')) ? path.join(L.CACHE_DIR, 'times.json') : path.join(L.FILM_DIR, 'render-times.json')), 'utf8'));
  say('RENDER TIMES (section caches, 1920x1080, SwiftShader / Canvas 2D on this machine):');
  for (const s of F.SECTIONS) { const t = times[s.slot]; if (t) say('       ' + s.slot.padEnd(20) + ' ' + String(t.frames).padStart(4) + ' frames, ' + t.secondsPerFramePerWorker.toFixed(2) + ' s/frame per worker, ' + t.workers + ' worker(s), wall ' + t.wallSeconds + ' s' + (t.ss ? ', supersampling ' + t.ss : '')); }
  if (fs.existsSync(path.join(L.FILM_DIR, 'compose-time.txt'))) say('       compositor: ' + fs.readFileSync(path.join(L.FILM_DIR, 'compose-time.txt'), 'utf8').trim());
  fs.writeFileSync(path.join(L.FILM_DIR, 'verification.txt'), out.join('\n') + '\n');
}
main().catch((e) => { console.error(e); process.exit(1); });
