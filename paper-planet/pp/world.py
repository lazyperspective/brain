SEAM0 = -165.0   # longitude of first gore seam
LATFOLD = 15.0


def px(lon, lat):
    return ((lon + 180.0) / 360.0 * TW, (90.0 - lat) / 180.0 * TH)


def _path(poly, shift=0.0):
    p = skia.Path()
    x, y = px(poly[0][0] + shift, poly[0][1])
    p.moveTo(x, y)
    for lo, la in poly[1:]:
        x, y = px(lo + shift, la)
        p.lineTo(x, y)
    p.close()
    return p


def _mask(polys, corner=5.0, stroke=None, closed=True):
    info = skia.ImageInfo.Make(TW, TH, skia.ColorType.kAlpha_8_ColorType, skia.AlphaType.kPremul_AlphaType)
    s = skia.Surface.MakeRaster(info)
    c = s.getCanvas()
    p = skia.Paint(AntiAlias=True)
    p.setColor4f(skia.Color4f(0, 0, 0, 1))
    if corner:
        p.setPathEffect(skia.CornerPathEffect.Make(corner))
    if stroke:
        p.setStyle(skia.Paint.kStroke_Style)
        p.setStrokeWidth(stroke)
        p.setStrokeCap(skia.Paint.kRound_Cap)
        p.setStrokeJoin(skia.Paint.kRound_Join)
    for poly in polys:
        for sh in (-360.0, 0.0, 360.0):
            lons = [q[0] + sh for q in poly]
            if max(lons) < -181 or min(lons) > 181:
                continue
            if closed:
                c.drawPath(_path(poly, sh), p)
            else:
                pa = skia.Path()
                pa.moveTo(*px(poly[0][0] + sh, poly[0][1]))
                for lo, la in poly[1:]:
                    pa.lineTo(*px(lo + sh, la))
                c.drawPath(pa, p)
    return s.toarray().reshape(TH, TW).astype(np.float32) / 255.0


def _coast_distance(land):
    """True angular distance (deg) from each ocean texel to nearest land, on a coarse grid."""
    h, w = TH // 4, TW // 4
    small = cv2.resize(land, (w, h), interpolation=cv2.INTER_AREA)
    lat = (90 - (np.arange(h) + 0.5) / h * 180) * np.pi / 180
    lon = ((np.arange(w) + 0.5) / w * 360 - 180) * np.pi / 180
    LO, LA = np.meshgrid(lon, lat)
    P = np.stack([np.cos(LA) * np.cos(LO), np.cos(LA) * np.sin(LO), np.sin(LA)], -1).reshape(-1, 3)
    m = small.reshape(-1) > 0.5
    tree = cKDTree(P[m])
    d, _ = tree.query(P[~m], k=1)
    out = np.zeros(h * w, np.float32)
    out[~m] = np.degrees(2 * np.arcsin(np.clip(d / 2, 0, 1)))
    out = out.reshape(h, w)
    out = cv2.GaussianBlur(out, (0, 0), 1.0)
    return cv2.resize(out, (TW, TH), interpolation=cv2.INTER_CUBIC)


def bake(force=False):
    os.makedirs(CACHE, exist_ok=True)
    f = os.path.join(CACHE, 'world_v9.npz')
    if os.path.exists(f) and not force:
        d = np.load(f)
        return {k: d[k] for k in d.files}
    rng = np.random.default_rng(11)
    lat = 90 - (np.arange(TH) + 0.5) / TH * 180
    lon = (np.arange(TW) + 0.5) / TW * 360 - 180
    LON, LAT = np.meshgrid(lon.astype(np.float32), lat.astype(np.float32))
    coslat = np.maximum(np.cos(np.radians(LAT)), 0.05)

    masks = {g: _mask(polys) for g, polys in LAND.items()}
    eur = _mask([EUROPE_REGION], corner=8)
    eu_from_as = masks['as'] * eur
    masks['eu'] = np.maximum(masks['eu'], eu_from_as)
    masks['as'] = masks['as'] * (1 - eur)
    lakes = _mask(LAKES, corner=4)
    rivers = _mask(RIVERS, corner=10, stroke=5.5, closed=False)
    land = np.clip(sum(masks.values()), 0, 1)
    water_in = np.clip(lakes + rivers, 0, 1) * land

    # ocean layers by true distance from coast, with hand-cut wobble
    dist = _coast_distance(np.clip(land - lakes, 0, 1))
    wob = cv2.resize(rng.standard_normal((TH // 64, TW // 64)).astype(np.float32), (TW, TH), interpolation=cv2.INTER_CUBIC)
    wob2 = cv2.resize(rng.standard_normal((TH // 16, TW // 16)).astype(np.float32), (TW, TH), interpolation=cv2.INTER_CUBIC)
    dw = dist + 0.9 * wob + 0.35 * wob2

    def edge(v, t, soft=0.10):
        return np.clip((t - v) / soft + 0.5, 0, 1)

    b1 = edge(dw, 11.5)
    b2 = edge(dw, 6.0)
    b3 = edge(dw, 2.6)
    oc = [hexrgb(c) for c in OCEAN]
    alb = np.empty((TH, TW, 3), np.float32)
    alb[:] = oc[0]
    for b, c in ((b1, oc[1]), (b2, oc[2]), (b3, oc[3])):
        alb = alb * (1 - b[..., None]) + c * b[..., None]
    height = 0.45 * b1 + 0.45 * b2 + 0.45 * b3

    # wave scribbles (little glued paper strips), drawn with latitude-compensated width
    surf = make_surface(TW, TH)
    c = surf.getCanvas()
    c.clear(skia.Color4f(0, 0, 0, 0))
    p = skia.Paint(AntiAlias=True, Style=skia.Paint.kStroke_Style)
    p.setStrokeCap(skia.Paint.kRound_Cap)
    p.setStrokeJoin(skia.Paint.kRound_Join)
    for la in np.arange(-66, 78, 5.6):
        cl = max(0.2, math.cos(math.radians(la)))
        step = 10.5 / cl
        off = rng.uniform(0, step)
        for lo in np.arange(-180 + off, 180, step):
            lo2 = lo + rng.uniform(-3.0, 3.0) / cl
            la2 = la + rng.uniform(-2.0, 2.0)
            x, y = px(lo2, la2)
            xi, yi = int(x) % TW, int(np.clip(y, 0, TH - 1))
            if dist[yi, xi] < 3.6 or land[yi, xi] > 0.01:
                continue
            if abs(la2) > 62 and rng.random() < 0.5:
                continue
            deep = dw[yi, xi] > 11.5
            sc = rng.uniform(0.8, 1.25)
            wdeg = 2.3 * sc
            hdeg = 0.42 * sc
            n = 2 if rng.random() < 0.7 else 3
            pa = skia.Path()
            ppd = TW / 360.0
            x0 = x - wdeg * ppd / cl * n / 2
            pa.moveTo(x0, y)
            for i in range(n):
                xa = x0 + (i + 0.5) * wdeg * ppd / cl
                xb = x0 + (i + 1) * wdeg * ppd / cl
                pa.quadTo(xa, y - hdeg * ppd * 2.2, xb, y)
            cc = hexrgb('#5FA8EC') if deep else hexrgb('#A9DBF8')
            p.setColor4f(skia.Color4f(float(cc[0]), float(cc[1]), float(cc[2]), 0.95 if deep else 0.9))
            p.setStrokeWidth(0.36 * ppd * sc)
            for sh in (-TW, 0, TW):
                c.save()
                c.translate(sh, 0)
                c.drawPath(pa, p)
                c.restore()
    scr = surf.toarray().astype(np.float32) / 255.0
    sa = scr[..., 3:4]
    alb = alb * (1 - sa) + scr[..., :3]
    height += 0.3 * sa[..., 0]

    # land
    for g in ('na', 'sa', 'af', 'as', 'eu', 'oc', 'ice'):
        m = masks[g][..., None]
        alb = alb * (1 - m) + hexrgb(PAL[g][0]) * m
    height = height * (1 - land) + land * 2.6
    for g, tone, poly in INNER:
        m = _mask([poly], corner=14) * masks[g]
        m3 = m[..., None]
        alb = alb * (1 - m3) + hexrgb(PAL[g][tone]) * m3
        height += 0.55 * m
    # rivers and lakes: cut-outs showing a pale blue sheet beneath
    w3 = water_in[..., None]
    alb = alb * (1 - w3) + hexrgb(RIVER) * w3
    height = height * (1 - water_in) + water_in * 1.7

    # per-gore tone variation, seams, latitude folds
    gw = 360.0 / GORES
    gl = np.mod(LON - SEAM0, gw)                 # 0..gw across the gore
    gi = np.floor(np.mod(LON - SEAM0, 360.0) / gw).astype(np.int32)
    tone = 1.0 + (rng.uniform(-1, 1, GORES).astype(np.float32) * 0.022)[gi]
    alb *= tone[..., None]
    dseam = np.minimum(gl, gw - gl) * coslat      # true degrees from seam
    ocean_only = 1.0 - land
    seam_dark = np.exp(-(dseam / 0.16) ** 2)
    alb *= (1.0 - 0.30 * seam_dark * (0.55 + 0.45 * ocean_only))[..., None]
    # overlap lip: each gore's east edge sits on top of the next one
    lip = np.clip(1.0 - (gw - gl) * coslat / 0.9, 0, 1) * (gl > gw / 2)
    height += 0.35 * lip
    fl = np.mod(LAT + LATFOLD / 2, LATFOLD) - LATFOLD / 2
    fold_dark = np.exp(-(fl / 0.11) ** 2) * (np.abs(LAT) < 80)
    alb *= (1.0 - 0.12 * fold_dark)[..., None]

    # baked contact shadow from stacked layers (light independent)
    hb = cv2.GaussianBlur(height, (0, 0), 5.0)
    ao = np.clip((hb - height) * 0.38, 0, 0.42)
    alb *= (1.0 - ao)[..., None]

    hs = cv2.GaussianBlur(height, (0, 0), 1.25)
    gx = cv2.Sobel(hs, cv2.CV_32F, 1, 0, ksize=3) / 8.0 / coslat
    gy = -cv2.Sobel(hs, cv2.CV_32F, 0, 1, ksize=3) / 8.0   # +gy = height increasing northwards
    gx = np.clip(gx, -1.2, 1.2)
    gy = np.clip(gy, -1.2, 1.2)

    out = {
        'albedo': (np.clip(alb, 0, 1) * 255 + 0.5).astype(np.uint8),
        'grad': np.stack([gx, gy], -1).astype(np.float16),
        'land': (land * 255).astype(np.uint8),
    }
    np.savez(f, **out)
    return out


def land_lookup():
    w = bake()
    return w['land']
